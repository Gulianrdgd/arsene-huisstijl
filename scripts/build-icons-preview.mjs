// Generates design-system/components/Iconen/preview.html from assets/icons/*.svg,
// with the SVGs inlined so they take the text colour (currentColor).
//   node scripts/build-icons-preview.mjs
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';

const icons = new URL('../assets/icons/', import.meta.url);
const outDir = new URL('../design-system/components/Iconen/', import.meta.url);
const names = (await readdir(icons)).filter((f) => f.endsWith('.svg')).sort();

const cells = [];
for (const file of names) {
	const svg = (await readFile(new URL(file, icons), 'utf8')).trim().replace('<svg ', '<svg aria-hidden="true" width="24" height="24" ');
	cells.push(`<div class="cell">${svg}<span>${file.replace('.svg', '')}</span></div>`);
}

const html = `<!-- @dsCard group="Merk" height=${Math.ceil(names.length / 6) * 76 + 140} -->
<!doctype html>
<html lang="nl">
<head><meta charset="utf-8"><title>Iconen</title><link rel="stylesheet" href="../../tokens.css"><link rel="stylesheet" href="../bundle.css">
<style>
body{margin:0;padding:24px}
.sizes{display:flex;gap:28px;align-items:center;margin-bottom:28px;color:var(--web-text)}
.grid{display:grid;grid-template-columns:repeat(6,1fr);gap:4px 12px}
.cell{display:flex;align-items:center;gap:10px;height:40px;color:var(--web-text)}
.cell span{font-family:var(--font-mono);font-size:11px;color:var(--web-text-muted)}
</style></head>
<body class="ar">
<!-- Generated by scripts/build-icons-preview.mjs from assets/icons/. -->
<div class="sizes">
  <span class="ar-meta">16, 20, 24 px</span>
  ${[16, 20, 24].map((s) => (cells.find((c) => c.includes('<span>arrow-right<')) || '').replace(/width="24" height="24"/, `width="${s}" height="${s}"`).replace(/<div class="cell">|<span>.*<\/span><\/div>/g, '')).join('\n  ')}
  <a class="ar-button" href="#">Begin een gesprek ${(cells.find((c) => c.includes('arrow-right')) || '').replace(/<div class="cell">|<span>.*<\/span><\/div>/g, '').replace(/width="24" height="24"/, 'width="18" height="18"')}</a>
</div>
<div class="grid">
${cells.join('\n')}
</div>
</body>
</html>
`;

await mkdir(outDir, { recursive: true });
await writeFile(new URL('preview.html', outDir), html);
console.log(`wrote Iconen/preview.html (${names.length} icons)`);
